DROP TABLE TBL_MEMBER CASCADE CONSTRAINT;
DROP TABLE TBL_MONEY CASCADE CONSTRAINT;

CREATE TABLE TBL_MEMBER(
CUSTNO NUMBER(6) PRIMARY KEY,
CUSTNAME VARCHAR2(20),
PHONE VARCHAR2(13),
ADDRESS VARCHAR2(60),
JOINDATE DATE,
GRADE CHAR(1),
CITY CHAR(2)
);

CREATE TABLE TBL_MONEY(
CUSTNO NUMBER(6),
SALENO NUMBER(8),
PCOST NUMBER(8),
AMOUNT NUMBER(4),
PRICE NUMBER(8),
PCODE VARCHAR2(4),
SDATE DATE,
CONSTRAINT PK_MONEY PRIMARY KEY(CUSTNO, SALENO),
CONSTRAINT FK_CUSTNO FOREIGN KEY(CUSTNO) REFERENCES TBL_MEMBER(CUSTNO)
);

